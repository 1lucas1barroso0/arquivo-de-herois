export function translateRuleText(
  value: string,
  language: AppLanguage,
): string {
  if (language === "pt") return value;
  const exact = translateUi(value, language);
  if (exact !== value) return exact;
  return englishRuleTerms.reduce(
    (translated, [portuguese, english]) =>
      translated.replaceAll(portuguese, english),
    value,
  );
}

export function buildTypeLabel(
  type: "hero" | "npc",
  language: AppLanguage = "pt",
): string {
  if (type === "npc") return "NPC";
  return language === "en" ? "Player Character" : "Personagem do Jogador";
}

export function languageName(language: AppLanguage): string {
  return language === "pt" ? "Português" : "English";
}
