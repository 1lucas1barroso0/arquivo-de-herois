export function translateUi(value: string, language: AppLanguage): string {
  if (language === "pt") return value;
  const exact = englishUi[value];
  if (exact) return exact;
  const numberedSection = value.match(/^(\d{2}) · (.+)$/);
  if (numberedSection) {
    return `${numberedSection[1]} · ${englishUi[numberedSection[2]] ?? numberedSection[2]}`;
  }
  return value;
}

