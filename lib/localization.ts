export function localizeConditionLabel(value: string, language: AppLanguage): string {
  const match = value.match(/^(.+?)\s*\(([^()]*)\)$/);
  if (!match) return translateUi(value, language);
  return language === "en" ? match[2].trim() : match[1].trim();
}
